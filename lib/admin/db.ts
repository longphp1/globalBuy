type Statement = {
  all: (...args: unknown[]) => Promise<Record<string, unknown>[]>;
  get: (...args: unknown[]) => Promise<Record<string, unknown> | undefined>;
  run: (...args: unknown[]) => Promise<{ lastInsertRowid: number | bigint; changes: number }>;
};

export type SqlDb = {
  exec: (sql: string) => Promise<void>;
  prepare: (sql: string) => Statement;
  syncIds: () => Promise<void>;
};

type RawSqlite = {
  exec: (sql: string) => void;
  prepare: (sql: string) => {
    all: (...args: unknown[]) => Record<string, unknown>[];
    get: (...args: unknown[]) => Record<string, unknown> | undefined;
    run: (...args: unknown[]) => { lastInsertRowid: number | bigint; changes: number };
  };
};

const globalState = globalThis as unknown as {
  adminSqlite?: SqlDb;
  adminPg?: postgres.Sql;
  adminSchema?: Promise<void>;
  adminSeed?: Promise<void>;
};


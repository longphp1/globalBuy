function cleanDatabaseUrl(raw: string) {
  const value = raw.trim().replace(/^["']|["']$/g, "");
  if (!value) return "";
  try {
    const parsed = new URL(value);
    const sslmode = parsed.searchParams.get("sslmode");
    parsed.search = "";
    if (sslmode) parsed.searchParams.set("sslmode", sslmode);
    return parsed.toString();
  } catch {
    return value;
  }
}

function envValue(...names: string[]) {
  for (const name of names) {
    const value = process.env[name]?.trim();
    if (value) return value;
  }
  return "";
}

export function databaseUrl() {
  if (process.env.VERCEL !== "1") return "";
  return cleanDatabaseUrl(
    envValue(
      "SUPABASE_DB_URL",
      "WEIDIAN_POSTGRES_URL",
      "WEIDIAN_POSTGRES_URL_NON_POOLING",
      "WEIDIAN_POSTGRES_PRISMA_URL",
      "POSTGRES_URL",
      "POSTGRES_PRISMA_URL",
      "DATABASE_URL",
      "POSTGRES_URL_NON_POOLING",
    ),
  );
}

function now() {
  return new Date().toISOString().slice(0, 19).replace("T", " ");
}

function slugify(value: string) {
  const slug = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
  return slug || "product";
}

function dbFile() {
  const dir = path.join(process.cwd(), "data");
  fs.mkdirSync(dir, { recursive: true });
  return path.join(dir, "admin.sqlite");
}

function toPostgres(sql: string) {
  let next = sql.trim().replace(/;+\s*$/, "");
  if (/^\s*insert\s+into\s+(products|sites|menus)\b/i.test(next) && !/\breturning\b/i.test(next)) {
    next = `${next} RETURNING id`;
  }
  let index = 0;
  return next.replace(/\?/g, () => `$${++index}`);
}

function wrapSqlite(raw: RawSqlite): SqlDb {
  return {
    async syncIds() {},
    async exec(sql: string) {
      raw.exec(sql);
    },
    prepare(sql: string): Statement {
      const statement = raw.prepare(sql);
      return {
        async all(...args) {
          return statement.all(...args);
        },
        async get(...args) {
          return statement.get(...args);
        },
        async run(...args) {
          return statement.run(...args);
        },
      };
    },
  };
}

function wrapPostgres(sql: postgres.Sql): SqlDb {
  let reserved: postgres.ReservedSql | null = null;
  const current = () => reserved ?? sql;

  return {
    async syncIds() {
      for (const table of ["products", "sites", "menus"]) {
        await current().unsafe(
          `SELECT setval(pg_get_serial_sequence('${table}', 'id'), max_id, true)
           FROM (SELECT MAX(id) AS max_id FROM ${table}) ids
           WHERE max_id IS NOT NULL`,
        );
      }
    },
    async exec(statement: string) {
      for (const part of statement.split(";").map((item) => item.trim()).filter(Boolean)) {
        if (/^PRAGMA/i.test(part)) continue;
        if (part === "BEGIN") {
          if (!reserved) reserved = await sql.reserve();
          await reserved.unsafe("BEGIN");
          continue;
        }
        if (part === "COMMIT" || part === "ROLLBACK") {
          if (!reserved) continue;
          try {
            await reserved.unsafe(part);
          } finally {
            reserved.release();
            reserved = null;
          }
          continue;
        }
        await current().unsafe(toPostgres(part));
      }
    },
    prepare(text: string): Statement {
      const query = toPostgres(text);
      return {
        async all(...args) {
          const rows = await current().unsafe(query, args as never[]);
          return [...rows] as Record<string, unknown>[];
        },
        async get(...args) {
          const rows = await current().unsafe(query, args as never[]);
          return rows[0] as Record<string, unknown> | undefined;
        },
        async run(...args) {
          const rows = await current().unsafe(query, args as never[]);
          const first = rows[0] as { id?: number | string } | undefined;
          return {
            lastInsertRowid: first?.id == null ? 0 : Number(first.id),
            changes: rows.count ?? 0,
          };
        },
      };
    },
  };
}

async function insertRows(db: SqlDb, table: string, columns: string[], rows: unknown[][]) {
  const width = columns.length;
  const batchSize = Math.max(1, Math.floor(5000 / width));
  for (let index = 0; index < rows.length; index += batchSize) {
    const chunk = rows.slice(index, index + batchSize);
    const values = chunk.map(() => `(${columns.map(() => "?").join(", ")})`).join(", ");
    await db.prepare(`INSERT INTO ${table} (${columns.join(", ")}) VALUES ${values}`).run(...chunk.flat());
  }
}

async function seed(db: SqlDb) {
  const existing = await db.prepare("SELECT COUNT(*) AS count FROM sites").get();
  if (Number(existing?.count ?? 0) > 0) {
    await db.syncIds();
    return;
  }

  const stamp = seedCatalog.generatedAt?.slice(0, 19).replace("T", " ") || now();
  const menuIds = new Map<string, number>();
  let menuId = 1;
  const siteRows: unknown[][] = [];
  const menuRows: unknown[][] = [];
  const productRows: unknown[][] = [];
  const seenCatalogs = new Set<string>();

  seedCatalog.sites.forEach((site, index) => {
    const siteId = index + 1;
    const catalogId = Number(site.siteId) || 1;
    siteRows.push([siteId, catalogId, site.slug, site.name, site.url, site.title]);
    if (seenCatalogs.has(String(catalogId))) return;
    seenCatalogs.add(String(catalogId));
    const data = seedCatalog.catalogs[String(catalogId)];
    if (!data) return;
    for (const menu of data.menus) {
      menuIds.set(`${catalogId}:${menu.url}`, menuId);
      menuRows.push([menuId, siteId, menu.name, menu.url]);
      menuId += 1;
    }
    data.products.forEach((product, indexInCatalog) => {
      const range = indexInCatalog + 1;
      const linkedMenu = menuIds.get(`${catalogId}:${product.menuUrl}`) ?? menuIds.get(`${catalogId}:home`) ?? 0;
      const source = product.sourceProductUrl.includes("weidian")
        ? "WD"
        : product.sourceProductUrl.includes("taobao")
          ? "TB"
          : "";
      productRows.push([
        product.id,
        siteId,
        linkedMenu,
        Math.ceil(range / 100),
        range,
        product.name,
        product.price,
        product.brand,
        source,
        product.sourceProductId,
        product.sourceProductUrl,
        product.image,
        "",
        product.sourceProductUrl,
        source === "WD" ? "weidian" : source === "TB" ? "taobao" : "",
        "",
        "",
        "",
        "",
        product.taoBuyLink ? "Open TaooBuy Link" : "",
        product.taoBuyLink,
        product.slug,
        stamp,
        stamp,
      ]);
    });
  });

  await db.exec("BEGIN");
  try {
    await insertRows(db, "sites", ["id", "catalog_id", "slug", "name", "url", "title"], siteRows);
    await insertRows(db, "menus", ["id", "site_id", "name", "url"], menuRows);
    await insertRows(
      db,
      "products",
      [
        "id", "site_id", "menu_id", "page", "range", "name", "price", "brand", "source", "source_product_id",
        "source_product_url", "main_img", "img", "main_buy_link", "main_buy_platform", "other_buy_link",
        "other_buy_platform", "note_link", "note_content", "tao_buy_platform", "tao_buy_link", "slug",
        "created_at", "updated_at",
      ],
      productRows,
    );
    await db.prepare("INSERT INTO meta (key, value) VALUES ('rev', '1')").run();
    await db.syncIds();
    await db.exec("COMMIT");
  } catch (error) {
    await db.exec("ROLLBACK");
    throw error;
  }
}

async function ensureReady(db: SqlDb, withSeed: boolean, schema: () => Promise<void>) {
  if (!globalState.adminSchema) {
    globalState.adminSchema = schema().catch((error) => {
      globalState.adminSchema = undefined;
      throw error;
    });
  }
  await globalState.adminSchema;
  if (!withSeed) return;
  if (!globalState.adminSeed) {
    globalState.adminSeed = seed(db).catch((error) => {
      globalState.adminSeed = undefined;
      throw error;
    });
  }
  await globalState.adminSeed;
}

async function openSqlite(withSeed: boolean) {
  if (!globalState.adminSqlite) {
    const { DatabaseSync } = await import("node:sqlite");
    globalState.adminSqlite = wrapSqlite(new DatabaseSync(dbFile()) as RawSqlite);
  }
  const db = globalState.adminSqlite;
  await ensureReady(db, withSeed, async () => {
    await db.exec(`
      PRAGMA journal_mode = WAL;
      CREATE TABLE IF NOT EXISTS sites (
        id INTEGER PRIMARY KEY,
        catalog_id INTEGER NOT NULL,
        slug TEXT NOT NULL,
        name TEXT NOT NULL,
        url TEXT,
        title TEXT,
        buy_link TEXT
      );
      CREATE TABLE IF NOT EXISTS menus (
        id INTEGER PRIMARY KEY,
        site_id INTEGER NOT NULL,
        name TEXT NOT NULL,
        url TEXT NOT NULL
      );
      CREATE TABLE IF NOT EXISTS products (
        id INTEGER PRIMARY KEY,
        site_id INTEGER NOT NULL,
        menu_id INTEGER NOT NULL,
        page INTEGER,
        range INTEGER,
        name TEXT,
        price TEXT,
        brand TEXT,
        source TEXT,
        source_product_id TEXT,
        source_product_url TEXT,
        main_img TEXT,
        img TEXT,
        main_buy_link TEXT,
        main_buy_platform TEXT,
        other_buy_link TEXT,
        other_buy_platform TEXT,
        note_link TEXT,
        note_content TEXT,
        tao_buy_platform TEXT,
        tao_buy_link TEXT,
        slug TEXT,
        created_at TEXT,
        updated_at TEXT
      );
      CREATE TABLE IF NOT EXISTS meta (
        key TEXT PRIMARY KEY,
        value TEXT
      );
      CREATE INDEX IF NOT EXISTS idx_products_name ON products(name);
      CREATE INDEX IF NOT EXISTS idx_products_brand ON products(brand);
      CREATE INDEX IF NOT EXISTS idx_products_menu ON products(menu_id);
    `);
    const columns = await db.prepare("PRAGMA table_info(sites)").all();
    if (!columns.some((column) => column.name === "buy_link")) {
      await db.exec("ALTER TABLE sites ADD COLUMN buy_link TEXT");
    }
  });
  return db;
}

async function openPostgres(url: string, withSeed: boolean) {
  if (!globalState.adminPg) {
    const { default: postgres } = await import("postgres");
    const local = /localhost|127\.0\.0\.1/.test(url);
    globalState.adminPg = postgres(url, {
      max: 1,
      idle_timeout: 20,
      connect_timeout: 30,
      prepare: false,
      ssl: local ? false : "require",
    });
  }
  const db = wrapPostgres(globalState.adminPg);
  await ensureReady(db, withSeed, async () => {
    for (const statement of POSTGRES_SCHEMA) await db.exec(statement);
  });
  return db;
}

export async function getDb(options?: { seed?: boolean }): Promise<SqlDb> {
  const withSeed = options?.seed !== false;
  if (process.env.VERCEL === "1") {
    const url = databaseUrl();
    if (!url) {
      throw new Error(
        "This deployment runs on Vercel and saves data in Supabase. Set WEIDIAN_POSTGRES_URL or SUPABASE_DB_URL to the database connection string, then redeploy.",
      );
    }
    return openPostgres(url, withSeed);
  }
  return openSqlite(withSeed);
}

export async function readPublishedCatalog(): Promise<Catalog | null> {
  if (!databaseUrl()) return null;
  try {
    const db = await getDb({ seed: false });
    const row = await db.prepare("SELECT value FROM meta WHERE key = ?").get("published_catalog");
    const raw = row?.value;
    if (typeof raw !== "string" || !raw) return null;
    return JSON.parse(raw) as Catalog;
  } catch {
    return null;
  }
}

export async function touch(db: SqlDb) {
  const row = await db.prepare("SELECT value FROM meta WHERE key = 'rev'").get();
  const next = Number(row?.value ?? 0) + 1;
  await db.prepare("INSERT INTO meta (key, value) VALUES ('rev', ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value").run(String(next));
}

export async function revision(db: SqlDb) {
  return Number((await db.prepare("SELECT value FROM meta WHERE key = 'rev'").get())?.value ?? 0);
}

export async function uniqueSlug(db: SqlDb, name: string, ignoreId = 0) {
  const base = slugify(name);
  let slug = base;
  let n = 2;
  while (await db.prepare("SELECT id FROM products WHERE slug = ? AND id != ?").get(slug, ignoreId)) {
    slug = `${base}-${n}`;
    n += 1;
  }
  return slug;
}

